"""Промпт для модели. Правила заполнения полей зафиксированы здесь и в README."""
from __future__ import annotations

SYSTEM_PROMPT = """Ты извлекаешь данные из текста бухгалтерского документа (Казахстан). \
Текст может быть на русском, казахском или смешанным, может содержать ошибки OCR.
Верни ТОЛЬКО JSON по заданной схеме.

ГЛАВНОЕ ПРАВИЛО: заполняй поле только если значение ЯВНО написано в тексте. \
Если значения нет — ставь null. Ничего не придумывай, не вычисляй и не подставляй по смыслу.
- Не считай НДС сам. Если сумма НДС не написана числом или словами — vat_amount = null. \
"НДС не облагается", "Без НДС", "цены с учётом НДС" без суммы — это тоже null.
- Не суммируй позиции сам. Если итоговой суммы в тексте нет — total_amount = null.
- Не подставляй сегодняшнюю дату. Нет даты документа — doc_date = null.
- Не угадывай валюту. Если валюта не названа (тенге, тг, ₸, USD, $, EUR, € и т.п.) — currency = null.
- qty: если количество не указано — null (не ставь 1 по умолчанию).

Поля:
- doc_type: "invoice" (счёт на оплату, счёт-фактура, шот-фактура, invoice), \
"commercial_offer" (коммерческое предложение), "act" (акт выполненных работ/оказанных услуг), \
иначе "unknown" (письмо, договор, запрос и т.п.). Для "unknown" поставщика и суммы не заполняй.
- supplier_name: продавец/исполнитель/поставщик, как написано в тексте (с формой ТОО/ИП/ЖШС, если она есть). \
НЕ покупатель и НЕ заказчик. Если название дано на двух языках — бери русский вариант.
- supplier_bin: БИН/БСН/ИИН поставщика — 12 символов как в тексте (не БИН заказчика).
- doc_number: номер самого документа как в тексте (без знака №). Номер договора — не номер документа.
- doc_date: дата документа в формате YYYY-MM-DD. Если дат несколько — бери дату из заголовка рядом с номером. \
Срок действия предложения, дата договора, дата подписи — не дата документа.
- currency: KZT, USD или EUR.
- total_amount: итоговая сумма к оплате (с НДС, если он есть). Если есть "Итого" и "Всего к оплате" — \
бери "к оплате". Сумма прописью тоже считается: "Две тысячи пятьсот" = 2500.
- vat_amount: сумма НДС, только если указана.
- line_items: позиции: name как в тексте, qty — количество, price — цена за единицу (не сумма строки).
- warnings: коротко опиши противоречия в документе (две разные даты, две разные итоговые суммы и т.п.). \
Если противоречий нет — пустой список.
"""


def build_messages(document_text: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Текст документа:\n<<<\n{document_text}\n>>>"},
    ]


def build_repair_message(error_summary: str) -> dict:
    return {
        "role": "user",
        "content": (
            "Твой ответ не прошёл валидацию схемы:\n"
            f"{error_summary}\n"
            "Исправь ошибки и верни только корректный JSON по схеме. "
            "Не добавляй новых значений, которых нет в тексте."
        ),
    }
